import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
const dir = 'docs/qa/evidence/blackbox-2026-09-15';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const origin = process.env.PLAYWRIGHT_BASE_URL || 'http://localhost:3000';
const rows = [];
async function capture(label) {
  const row = { label, url: page.url(), snapshot: await page.locator('body').ariaSnapshot() };
  rows.push(row); console.log(JSON.stringify(row));
  await page.screenshot({ path: `${dir}/${label}.png`, fullPage: true });
}
await page.goto(origin + '/katalog');
await page.getByText('Loading catalog items...').waitFor({ state: 'hidden' });
await page.getByRole('textbox', { name: 'Search' }).fill('qa-no-result-20260915');
await capture('search-empty');
await page.getByRole('textbox', { name: 'Search' }).fill('');
await page.getByRole('button', { name: /Tambah .* ke Keranjang/ }).first().dblclick();
await page.getByRole('banner').getByRole('link', { name: 'Cart', exact: true }).click();
await page.waitForURL('**/cart');
await page.getByRole('heading', { name: 'YOUR CART' }).waitFor();
await capture('double-add-cart');
console.log(JSON.stringify({cartButtons: await page.getByRole('main').getByRole('button').evaluateAll(nodes=>nodes.map(n=>n.outerHTML))}));
await page.getByRole('button', { name: /^Select / }).first().click();
await capture('cart-deselected');
while(await page.getByRole('button', { name: /^Remove / }).count()) await page.getByRole('button', { name: /^Remove / }).first().click();
await page.getByText('Your Cart is Empty', { exact: true }).waitFor();
await page.reload();
await page.getByText('Your Cart is Empty', { exact: true }).waitFor();
await capture('empty-after-remove-refresh');
await page.goto(origin + '/katalog');
await page.getByText('Loading catalog items...').waitFor({ state: 'hidden' });
await page.getByRole('link').filter({ has: page.getByRole('heading', { level: 3 }) }).first().click();
await page.waitForURL('**/produk/**');
await page.getByRole('heading', { level: 1 }).waitFor();
console.log(JSON.stringify({detailButtons: await page.getByRole('main').getByRole('button').evaluateAll(nodes=>nodes.map(n=>({text:n.textContent,label:n.getAttribute('aria-label'),title:n.getAttribute('title'),icon:n.querySelector('svg')?.getAttribute('class')})))}));
await page.getByRole('button', { name: 'Navy', exact: true }).click();
await page.getByRole('button', { name: 'Add to Cart', exact: true }).first().click();
await page.getByRole('banner').getByRole('link', { name: 'Cart', exact: true }).click();
await page.waitForURL('**/cart');
await page.getByRole('heading', { name: 'YOUR CART' }).waitFor();
await capture('cart-navy');
const outbound = page.context().waitForEvent('request', { predicate: r => r.isNavigationRequest() && /wa\.me|whatsapp\.com/.test(new URL(r.url()).hostname) });
await page.getByRole('button', { name: 'ORDER (1)' }).click();
const orderRequest = await outbound;
const orderUrl = new URL(orderRequest.url());
const orderObservation = { label: 'cart-order-composer', host: orderUrl.hostname, text: orderUrl.searchParams.get('text') };
rows.push(orderObservation); console.log(JSON.stringify(orderObservation));
for (const popup of page.context().pages()) if (popup !== page) await popup.close();
await page.goto(origin + '/produk/qa-no-such-product-20260915');
await page.getByRole('main').waitFor();
await capture('unknown-product');
await writeFile(`${dir}/state-discovery.json`, JSON.stringify(rows,null,2));
await browser.close();
